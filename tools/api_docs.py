"""Generate/check standalone audio inventories (adapted from VMNL's API tooling)."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import html
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
API_ROOT = ROOT / "docs/api"
MATRIX_PATH = API_ROOT / "maintenance/coverage_matrix.md"
PUBLIC_API_VERSION = "0.52.0"
PUBLIC_API_NIGHTLY = "nightly-2026-03-12"
GENERATED_NOTICE = "<!-- Generated by tools/api_docs.py; do not edit. -->"
KINDS = {"struct": "struct", "enum": "enum", "type_alias": "alias", "trait": "trait"}
PATH = r"vmnl_audio(?:::[A-Za-z_][A-Za-z0-9_]*)+"
ITEM_RE = re.compile(rf"^(?:#\[[^]]+]\s+)*pub (struct|enum|type|trait) ({PATH})(?:<|\s|$)")
METHOD_RE = re.compile(rf"^pub (?:const |async |unsafe )*fn ({PATH}(?:<.*?>)?(?:::[A-Za-z_][A-Za-z0-9_]*)?)\(")
MEMBER_RE = re.compile(rf"^pub ({PATH})(?:\(|: | = |$)")
LINK_RE = re.compile(r"^\[([^]]+)]\(([^)]+)\)$")


class ApiDocsError(RuntimeError):
    """Invalid or stale public documentation."""


@dataclass(frozen=True, order=True)
class PublicItem:
    kind: str
    symbol: str


@dataclass(frozen=True, order=True)
class PublicMethod:
    owner: str
    name: str


@dataclass(frozen=True)
class Surface:
    text: str
    items: tuple[PublicItem, ...]
    methods: tuple[PublicMethod, ...]
    members: tuple[PublicMethod, ...]
    aliases: dict[str, str]


@dataclass(frozen=True)
class CoverageRow:
    item: PublicItem
    page_target: str
    rustdoc_target: str
    evidence_target: str


def public_paths(document: dict) -> dict[str, str]:
    """Use rustdoc item IDs, never name similarity, to identify reexports."""
    if document.get("format_version") != 57:
        raise ApiDocsError("expected rustdoc JSON format 57 from the pinned nightly")
    index = document["index"]
    paths_by_id: dict[str, set[str]] = {}

    def visit(item_id: str, path: str, ancestors: frozenset[str]) -> None:
        if item_id in ancestors:
            raise ApiDocsError(f"cyclic public module reexport at {path}")
        item = index.get(item_id)
        if item is None or item["crate_id"] != 0:
            raise ApiDocsError(f"external public reexport needs explicit documentation support: {path}")
        inner = item["inner"]
        if "module" in inner:
            for child_id in inner["module"]["items"]:
                child = index[str(child_id)]
                if child["visibility"] != "public":
                    continue
                use = child["inner"].get("use")
                if use:
                    target = use.get("id")
                    if target is None:
                        raise ApiDocsError(f"unresolved public reexport in {path}")
                    child_path = path if use["is_glob"] else f"{path}::{use['name']}"
                    visit(str(target), child_path, ancestors | {item_id})
                else:
                    visit(str(child_id), f"{path}::{child['name']}", ancestors | {item_id})
        elif next(iter(inner)) in KINDS:
            paths_by_id.setdefault(item_id, set()).add(path)
        else:
            raise ApiDocsError(f"unsupported exported item in documentation inventory: {path}")

    visit(str(document["root"]), "vmnl_audio", frozenset())
    aliases = {}
    for paths in paths_by_id.values():
        canonical = min(paths, key=lambda path: (path.count("::"), path))
        aliases.update((path, canonical) for path in paths)
    return aliases


def strip_generics(path: str) -> str:
    result = []
    depth = 0
    for char in path:
        if char == "<":
            depth += 1
        elif char == ">":
            depth -= 1
        elif depth == 0:
            result.append(char)
    return "".join(result)


def parse_surface(text: str, aliases: dict[str, str]) -> Surface:
    items, methods, members = set(), set(), set()
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        if match := ITEM_RE.match(line):
            kind, path = match.groups()
            if path not in aliases:
                raise ApiDocsError(f"public item absent from rustdoc export graph: {path}")
            items.add(PublicItem("alias" if kind == "type" else kind, aliases[path]))
        elif match := METHOD_RE.match(line):
            owner, name = strip_generics(match[1]).rsplit("::", 1)
            if owner not in aliases:
                raise ApiDocsError(f"public method has no owning exported item: {owner}::{name}")
            methods.add(PublicMethod(aliases[owner], name))
        elif match := MEMBER_RE.match(line):
            owner, name = match[1].rsplit("::", 1)
            if owner not in aliases:
                raise ApiDocsError(f"public member has no owning exported item: {owner}::{name}")
            members.add(PublicMethod(aliases[owner], name))
        elif not re.match(r"^(pub mod |pub use |(?:unsafe )?impl[ <]|#\[)", line):
            raise ApiDocsError(f"unknown cargo-public-api inventory format: {line}")
    if not items:
        raise ApiDocsError("empty public inventory")
    missing = set(aliases.values()) - {item.symbol for item in items}
    if missing:
        raise ApiDocsError(f"exported items absent from text inventory: {sorted(missing)}")
    return Surface(text.rstrip() + "\n", tuple(sorted(items)), tuple(sorted(methods)),
                   tuple(sorted(members)), aliases)


def parse_link(cell: str) -> str:
    match = LINK_RE.fullmatch(cell.strip())
    if not match:
        raise ApiDocsError(f"expected one Markdown link: {cell!r}")
    return match[2]


def parse_matrix(path: Path = MATRIX_PATH) -> tuple[CoverageRow, ...]:
    rows, seen = [], set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        cells = [value.strip() for value in line.strip("|").split("|")]
        if cells[0] == "Kind" or set(cells[0]) <= {"-", ":"}:
            continue
        if len(cells) != 5 or cells[0] not in set(KINDS.values()):
            raise ApiDocsError(f"invalid coverage row: {line}")
        item = PublicItem(cells[0], cells[1].strip("`"))
        if item in seen:
            raise ApiDocsError(f"duplicate coverage item: {item.symbol}")
        seen.add(item)
        rows.append(CoverageRow(item, *(parse_link(cell) for cell in cells[2:])))
    if not rows:
        raise ApiDocsError("empty coverage matrix")
    return tuple(rows)


def local_target(base: Path, target: str) -> tuple[Path, str]:
    if re.match(r"[a-z][a-z0-9+.-]*:", target):
        raise ApiDocsError(f"coverage links must be local: {target}")
    path, _, anchor = target.partition("#")
    return (base / path).resolve(), anchor


def validate_coverage(surface: Surface, rows: tuple[CoverageRow, ...], matrix_path: Path = MATRIX_PATH) -> None:
    expected, actual = set(surface.items), {row.item for row in rows}
    if expected != actual:
        raise ApiDocsError(f"coverage mismatch; missing={sorted(expected - actual)}, stale={sorted(actual - expected)}")
    owners = {row.item.symbol: row for row in rows}
    for row in rows:
        for target in (row.page_target, row.rustdoc_target, row.evidence_target):
            path, anchor = local_target(matrix_path.parent, target)
            if not path.is_file():
                raise ApiDocsError(f"missing coverage target for {row.item.symbol}: {path}")
            if anchor:
                raise ApiDocsError("coverage links must target whole pages; method anchors are generated")
    for member in (*surface.methods, *surface.members):
        if member.owner not in owners:
            raise ApiDocsError(f"public method/member has no owning matrix item: {member}")
        row = owners[member.owner]
        page, _ = local_target(matrix_path.parent, row.page_target)
        if f"`{member.name}`" not in page.read_text(encoding="utf-8"):
            raise ApiDocsError(f"undocumented public method/member: {member.owner}::{member.name} in {page}")
    for method in surface.methods:
        page, _ = local_target(matrix_path.parent, owners[method.owner].rustdoc_target)
        if f'id="method.{html.escape(method.name)}"' not in page.read_text(encoding="utf-8"):
            raise ApiDocsError(f"missing Rustdoc method anchor: {method.owner}::{method.name}")


def render_outputs(surface: Surface, rows: tuple[CoverageRow, ...]) -> dict[Path, str]:
    symbols = [GENERATED_NOTICE, "# Public symbol index", "",
               "Each row is one rustdoc item identity; alternative paths are reexports, not extra types.", "",
               "| Kind | Canonical path | Other public paths | Page | Rustdoc |",
               "|---|---|---|---|---|"]
    owners = {row.item.symbol: row for row in rows}
    for row in sorted(rows, key=lambda row: row.item.symbol):
        aliases = ", ".join(f"`{path}`" for path, canonical in sorted(surface.aliases.items())
                            if canonical == row.item.symbol and path != canonical) or "—"
        symbols.append(f"| {row.item.kind} | `{row.item.symbol}` | {aliases} | "
                       f"[Page]({row.page_target}) | [Rustdoc]({row.rustdoc_target}) |")
    methods = [GENERATED_NOTICE, "# Method index", "",
               "Inherent and explicit/derived trait methods; blanket implementations are omitted.", "",
               "| Owner | Method | Page | Rustdoc |", "|---|---|---|---|"]
    for method in surface.methods:
        row = owners[method.owner]
        methods.append(f"| `{method.owner}` | `{method.name}` | [Page]({row.page_target}) | "
                       f"[Method]({row.rustdoc_target}#method.{method.name}) |")
    snapshot = (f"{GENERATED_NOTICE}\n# Public API snapshot\n\n"
                f"`cargo-public-api {PUBLIC_API_VERSION}`, `{PUBLIC_API_NIGHTLY}`; only blanket impls omitted. "
                "Paths below are preserved exactly; see the symbol index for identity-based aliases.\n\n"
                f"```text\n{surface.text}```\n")
    return {API_ROOT / "maintenance/public_api_snapshot.md": snapshot,
            API_ROOT / "appendices/public_symbol_index.md": "\n".join(symbols) + "\n",
            API_ROOT / "appendices/method_index.md": "\n".join(methods) + "\n"}


def verify_outputs(outputs: dict[Path, str]) -> None:
    stale = [str(path) for path, content in outputs.items()
             if not path.is_file() or path.read_text(encoding="utf-8") != content]
    if stale:
        raise ApiDocsError(f"stale generated inventory: {stale}; run just docs-api-update")


def command_surface() -> Surface:
    version = subprocess.check_output(["cargo-public-api", "--version"], text=True).strip()
    if version != f"cargo-public-api {PUBLIC_API_VERSION}":
        raise ApiDocsError(f"expected cargo-public-api {PUBLIC_API_VERSION}, got {version}")
    environment = {**os.environ, "CARGO_NET_OFFLINE": "true"}
    completed = subprocess.run(
        ["cargo", f"+{PUBLIC_API_NIGHTLY}", "public-api", "--manifest-path", "Cargo.toml",
         "--target-dir", "target/api-public-api", "--omit", "blanket-impls", "--color", "never"],
        cwd=ROOT, env=environment, check=True, text=True, stdout=subprocess.PIPE,
    )
    document = json.loads((ROOT / "target/api-public-api/doc/vmnl_audio.json").read_text())
    return parse_surface(completed.stdout, public_paths(document))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("check", "update"))
    args = parser.parse_args()
    try:
        surface = command_surface()
        rows = parse_matrix()
        validate_coverage(surface, rows)
        outputs = render_outputs(surface, rows)
        if args.mode == "update":
            for path, content in outputs.items():
                path.write_text(content, encoding="utf-8")
        else:
            verify_outputs(outputs)
        print(f"API: {len(surface.items)} items, {len(surface.aliases)} paths, {len(surface.methods)} methods")
    except (ApiDocsError, OSError, ValueError, KeyError, subprocess.CalledProcessError) as error:
        print(f"api-docs: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
